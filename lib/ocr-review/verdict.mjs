// lib/ocr-review/verdict.mjs -- OCR on Demand: the no-false-negative verdict
// (docs/design/OCR-ON-DEMAND.DESIGN.md: G4, Review job table, Verdict row).
//
// A run's reviewable files are the files git says changed in the range ocr
// resolved, minus a declared exclusion class -- deleted files, files git's
// own binary detection calls binary, files the repo's attributes at the head
// mark linguist-generated or linguist-vendored, and lockfiles from the fixed
// list below. This workflow decides that, never ocr's own file selection:
// upstream issue #1454 shipped a release that selected zero files on a
// non-empty diff and exited 0.
//
// The verdict then needs three things from the pinned engine: the resolved
// range, the per-file reviewed list (ocr's run manifest, schema
// ocr.run-manifest/v1: input.resolved_base/resolved_head and coverage), and
// the per-finding post status. Any of them missing or unparseable is
// engine-error -- never "nothing to compare" or "nothing failed".
//
// Everything here is pure: the git output arrives as text (bin/ocr-review
// runs git), ocr's result as text, the post status as a value.

// --- Constants --------------------------------------------------------------

/** Lockfiles, matched by file name in any directory (G4: a fixed list kept
 * in code). Generated by a package manager, never meaningfully reviewed. */
export const LOCKFILES = Object.freeze([
  'package-lock.json',
  'npm-shrinkwrap.json',
  'yarn.lock',
  'pnpm-lock.yaml',
  'bun.lock',
  'bun.lockb',
  'deno.lock',
  'Cargo.lock',
  'Gemfile.lock',
  'composer.lock',
  'poetry.lock',
  'uv.lock',
  'Pipfile.lock',
  'pdm.lock',
  'go.sum',
  'go.work.sum',
  'mix.lock',
  'flake.lock',
  'Podfile.lock',
  'pubspec.lock',
  'packages.lock.json',
  'gradle.lockfile',
  'Package.resolved',
  '.terraform.lock.hcl',
]);

const LOCKFILE_NAMES = new Set(LOCKFILES);

/** check-attr values that turn a linguist attribute on. */
const ATTRIBUTE_ON = new Set(['set', 'true']);

/** The per-finding post states the verdict understands. */
const POST_STATES = new Set(['inline', 'unanchorable', 'failed']);

// --- Predicates -------------------------------------------------------------

/** True for a path whose file name is on the lockfile list. */
export function isLockfile(path) {
  return LOCKFILE_NAMES.has(String(path).split('/').pop());
}

const isSha = (value) => typeof value === 'string' && /^[0-9a-f]{7,64}$/i.test(value);

// --- Pure helpers: git output -----------------------------------------------

/** `git diff --name-status -z --no-renames` -> [{ status, path }]. */
export function parseNameStatus(text) {
  const fields = String(text).split('\0').filter((f) => f !== '');
  const out = [];
  for (let i = 0; i + 1 < fields.length; i += 2) out.push({ status: fields[i].charAt(0), path: fields[i + 1] });
  return out;
}

/** `git diff --numstat -z --no-renames` -> the set of paths git calls binary. */
export function parseNumstat(text) {
  const binary = new Set();
  for (const record of String(text).split('\0')) {
    const match = record.match(/^-\t-\t(.+)$/s);
    if (match) binary.add(match[1]);
  }
  return binary;
}

/** `git check-attr -z linguist-generated linguist-vendored` -> Map path -> flags. */
export function parseCheckAttr(text) {
  const fields = String(text).split('\0');
  const attrs = new Map();
  for (let i = 0; i + 2 < fields.length; i += 3) {
    const [path, name, value] = [fields[i], fields[i + 1], fields[i + 2]];
    const entry = attrs.get(path) ?? { generated: false, vendored: false };
    if (name === 'linguist-generated') entry.generated = ATTRIBUTE_ON.has(value);
    if (name === 'linguist-vendored') entry.vendored = ATTRIBUTE_ON.has(value);
    attrs.set(path, entry);
  }
  return attrs;
}

/** The reviewable files: changed, minus the exclusion class; sorted. */
export function reviewableFiles({ changes, binary, attributes }) {
  return changes
    .filter(({ status }) => status !== 'D')
    .map(({ path }) => path)
    .filter((path) => !binary.has(path))
    .filter((path) => !attributes.get(path)?.generated && !attributes.get(path)?.vendored)
    .filter((path) => !isLockfile(path))
    .sort();
}

// --- Pure helpers: ocr's result ---------------------------------------------

/**
 * Read ocr's JSON result (`--audience agent --format json`). Returns
 * { ok: true, range, reviewed, findings } or { ok: false, missing: [...] }
 * naming every required part that is absent or unparseable.
 */
export function readEngineResult(text) {
  let parsed;
  try {
    parsed = JSON.parse(String(text));
  } catch {
    return { ok: false, missing: ['result'] };
  }
  if (!parsed || typeof parsed !== 'object') return { ok: false, missing: ['result'] };
  const missing = [];
  const input = parsed.manifest?.input;
  const range = isSha(input?.resolved_base) && isSha(input?.resolved_head) ? { base: input.resolved_base, head: input.resolved_head } : null;
  if (!range) missing.push('range');
  const coverage = parsed.manifest?.coverage;
  const lists = [coverage?.completed, coverage?.reused];
  const reviewed = lists.every(Array.isArray) ? [...new Set(lists.flat().map((item) => item?.path).filter(Boolean))].sort() : null;
  if (!reviewed) missing.push('reviewed files');
  const findings = Array.isArray(parsed.comments) ? parsed.comments : null;
  if (!findings) missing.push('findings');
  return missing.length > 0 ? { ok: false, missing } : { ok: true, range, reviewed, findings };
}

const engineError = (detail) => ({ outcome: 'failure', cause: 'engine-error', detail });

// --- Pure helpers: the verdict ----------------------------------------------

/**
 * The G4 verdict. `reviewable` is reviewableFiles' answer over the engine's
 * range; `engine` is readEngineResult's; `postStatus` is one of
 * inline | unanchorable | failed per finding, in the result's order, or
 * null when the engine did not expose it.
 */
export function judgeReview({ reviewable, engine, postStatus }) {
  if (!engine.ok) return engineError(`ocr's result lacks: ${engine.missing.join(', ')}`);
  if (!Array.isArray(postStatus)) return engineError('the engine exposed no per-finding post status');
  if (postStatus.length !== engine.findings.length || !postStatus.every((s) => POST_STATES.has(s))) {
    return engineError('the per-finding post status does not match the findings');
  }
  const reviewedSet = new Set(engine.reviewed);
  const covered = reviewable.filter((path) => reviewedSet.has(path));
  const unreviewed = reviewable.filter((path) => !reviewedSet.has(path));
  const unposted = engine.findings
    .map((finding, i) => ({ path: finding.path, line: finding.start_line || null, body: finding.content ?? '', status: postStatus[i] }))
    .filter((finding) => finding.status !== 'inline');
  const counts = {
    range: engine.range,
    filesReviewable: reviewable.length,
    filesReviewed: covered.length,
    findingsPosted: postStatus.filter((s) => s === 'inline').length,
    findingsFailed: postStatus.filter((s) => s === 'failed').length,
    unreviewed,
    unposted,
  };
  if (reviewable.length === 0) return { outcome: 'success', cause: 'nothing-reviewable', ...counts };
  if (covered.length === 0) {
    return { outcome: 'failure', cause: 'reviewed-nothing', detail: `${reviewable.length} reviewable files, none reviewed`, ...counts };
  }
  return { outcome: 'success', cause: null, ...counts };
}
